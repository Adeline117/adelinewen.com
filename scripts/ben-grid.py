#!/usr/bin/env python3
"""Turn a photo into the colour grid /ben draws in 0s and 1s.

Only the grid ships (160 x 118 cells of colour; the page samples it down to fit the screen), never the photo itself.

  python3 scripts/ben-grid.py PHOTO [--crop x0,y0,x1,y1] [--cols 160]
"""
import argparse
import base64
import os

from PIL import Image, ImageEnhance

ap = argparse.ArgumentParser()
ap.add_argument("photo")
ap.add_argument("--crop", default="0,340,1276,1860")  # photo area without the story bars and the sticker
ap.add_argument("--cols", type=int, default=160)
a = ap.parse_args()

CELL = 0.62  # a monospace digit is about 0.62 as wide as it is tall
im = Image.open(a.photo).convert("RGB").crop(tuple(int(v) for v in a.crop.split(",")))
rows = round(a.cols * im.height / im.width * CELL)
small = im.resize((a.cols, rows), Image.LANCZOS)
# digits on a dark sheet read dimmer than pixels: lift the mid-tones and colour a little
small = ImageEnhance.Contrast(small).enhance(1.15)
small = ImageEnhance.Color(small).enhance(1.2)
small = small.point(lambda v: round(255 * (v / 255) ** 0.85))

data = base64.b64encode(small.tobytes()).decode()
out = os.path.join(os.path.dirname(__file__), "..", "app", "ben", "grid.ts")
os.makedirs(os.path.dirname(out), exist_ok=True)
with open(out, "w") as f:
    f.write("// generated by scripts/ben-grid.py: the photo's colours, one RGB triple per cell\n")
    f.write(f"export const COLS = {a.cols};\nexport const ROWS = {rows};\n")
    f.write(f'export const RGB = "{data}";\n')
print(a.cols, rows, len(data), "chars")
