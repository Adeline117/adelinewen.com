#!/usr/bin/env python3
"""Turn a photo into the ink grid /ben draws in 0s and 1s.

Each cell gets one value, 0-255: how much ink its digit carries. Dark parts of the photo
and the edges of the figure carry the most; everything outside the subject (the mask from
scripts/ben-lift.py) carries none, so the picture is drawn by the digits themselves on
blank paper. Only this grid ships, never the photo.

  python3 scripts/ben-grid.py PHOTO MASK [--crop x0,y0,x1,y1] [--cols 160]
"""
import argparse
import base64
import os

import numpy as np
from PIL import Image, ImageFilter

ap = argparse.ArgumentParser()
ap.add_argument("photo")
ap.add_argument("mask")  # white = subject, same size as the cropped photo
ap.add_argument("--crop", default="0,340,1276,1860")  # photo area without the story bars and the sticker
ap.add_argument("--cols", type=int, default=160)
a = ap.parse_args()

CELL = 0.62  # a monospace digit is about 0.62 as wide as it is tall
photo = Image.open(a.photo).convert("L").crop(tuple(int(v) for v in a.crop.split(",")))
mask = Image.open(a.mask).convert("L").resize(photo.size)

# tone: darkness, stretched across the subject's own range; mid-tones pushed light so hair
# reads as solid ink and skin and sweater as a lighter hand
sharp = photo.filter(ImageFilter.UnsharpMask(radius=6, percent=160, threshold=2))
g = np.asarray(sharp, dtype=np.float32) / 255
m = np.asarray(mask, dtype=np.float32) / 255
d = 1 - g
lo, hi = np.percentile(d[m > 0.5], 4), np.percentile(d[m > 0.5], 98)
d = np.clip((d - lo) / (hi - lo), 0, 1) ** 2.0

# line: tonal edges inside the figure, plus the figure's own outline
blur = np.asarray(photo.filter(ImageFilter.GaussianBlur(3)), dtype=np.float32) / 255
gx = np.zeros_like(blur)
gy = np.zeros_like(blur)
gx[:, 1:-1] = blur[:, 2:] - blur[:, :-2]
gy[1:-1, :] = blur[2:, :] - blur[:-2, :]
e = np.hypot(gx, gy)
e = np.clip(e / np.percentile(e[m > 0.5], 97), 0, 1)
mb = np.asarray(mask.filter(ImageFilter.GaussianBlur(4)), dtype=np.float32) / 255
outline = np.clip(1 - np.abs(mb - 0.5) * 2, 0, 1)

v = np.clip(0.06 + 1.0 * d + 0.75 * np.maximum(e, 0.9 * outline), 0, 1) * np.clip(m * 1.4, 0, 1)
rows = round(a.cols * photo.height / photo.width * CELL)
grid = Image.fromarray((v * 255).astype(np.uint8)).resize((a.cols, rows), Image.BOX)

data = base64.b64encode(grid.tobytes()).decode()
out = os.path.join(os.path.dirname(__file__), "..", "app", "ben", "grid.ts")
with open(out, "w") as f:
    f.write("// generated by scripts/ben-grid.py: how much ink each cell's digit carries, 0-255\n")
    f.write(f"export const COLS = {a.cols};\nexport const ROWS = {rows};\n")
    f.write(f'export const INK = "{data}";\n')
print(a.cols, rows, len(data), "chars")
